// Generates src/components/lang-icons.ts from Devicon's colour logos (MIT,
// https://devicon.dev) so the compiler shows real language logos with no
// image requests. Gradient/clip ids are prefixed per language because several
// Devicon files reuse ids like "a", which would clash when inlined together.
//
//   node scripts/build-lang-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

// compiler language id → Devicon icon (+ dark: logo is black, so invert it on dark backgrounds)
const ICONS = {
  python: 'python', r: 'r', sql: 'sqlite', html: 'html5', java: 'java', kotlin: 'kotlin',
  c: 'c', cpp: 'cplusplus', csharp: 'csharp', javascript: 'javascript', typescript: 'typescript',
  go: 'go', rust: 'rust', scala: 'scala', dart: 'dart', ruby: 'ruby', php: 'php', swift: 'swift',
}
const DARK_INK = new Set(['rust'])

const out = {}
for (const [lang, icon] of Object.entries(ICONS)) {
  let svg = readFileSync(join(root, 'node_modules/devicon/icons', icon, `${icon}-original.svg`), 'utf8')
  svg = svg.replace(/<\?xml[^>]*>|<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim()
  const ids = [...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])
  for (const id of ids) {
    const safe = `li-${lang}-${id}`
    svg = svg.replaceAll(`id="${id}"`, `id="${safe}"`).replaceAll(`url(#${id})`, `url(#${safe})`).replaceAll(`"#${id}"`, `"#${safe}"`)
  }
  // Size comes from CSS; keep only the viewBox.
  svg = svg.replace(/<svg\b[^>]*>/, (tag) => `<svg ${tag.match(/viewBox="[^"]+"/)[0]} xmlns="http://www.w3.org/2000/svg" aria-hidden="true">`)
  out[lang] = { svg, invertOnDark: DARK_INK.has(lang) }
}

const body = `// Generated by scripts/build-lang-icons.mjs from Devicon (MIT, https://devicon.dev). Do not edit.

export const LANG_ICONS: Record<string, { svg: string; invertOnDark: boolean }> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(join(root, 'src/components/lang-icons.ts'), body)
console.log(`wrote ${Object.keys(out).length} icons`)
